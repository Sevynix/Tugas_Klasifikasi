import os
import warnings
import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler
from imblearn.over_sampling import SMOTE
from sklearn.tree import DecisionTreeClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVC
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score,
    f1_score, confusion_matrix, classification_report
)

warnings.filterwarnings('ignore')
print('Import library berhasil!')

"""## 2. Load Dataset"""

data_path = 'diabetes_dataset.csv' if os.path.exists('diabetes_dataset.csv') else 'TM8/diabetes_dataset.csv'
df = pd.read_csv(data_path)
print(f'Dimensi data: {df.shape[0]} baris, {df.shape[1]} kolom')
df.head()

# Cek missing value
print('Missing Value (isna):')
print(df.isna().sum())

"""## 3. Preprocessing
- Imputasi nilai 0 fisiologis (median)
- Hapus duplikat
- Capping outlier (IQR)
"""

df_clean = df.copy()

# 1. Imputasi nilai 0 fisiologis
zero_cols = ['Glucose', 'BloodPressure', 'SkinThickness', 'Insulin', 'BMI']
for col in zero_cols:
    median_val = df_clean[df_clean[col] != 0][col].median()
    df_clean[col] = df_clean[col].replace(0, median_val)
    print(f'- Imputasi {col:15s}: median = {median_val:.1f}')

# 2. Hapus duplikat
duplikat = df_clean.duplicated().sum()
print(f'\nJumlah duplikat: {duplikat}')
if duplikat > 0:
    df_clean = df_clean.drop_duplicates()

# 3. Capping outlier IQR
fitur_cols = [c for c in df_clean.columns if c not in ['Outcome', 'Insulin']]
for col in fitur_cols:
    Q1 = df_clean[col].quantile(0.25)
    Q3 = df_clean[col].quantile(0.75)
    IQR = Q3 - Q1
    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR
    df_clean[col] = np.clip(df_clean[col], lower, upper)

"""## 4. Split Data, Normalisasi & Resampling
- Split data 80:20 (stratified)
- Normalisasi MinMaxScaler
- Resampling SMOTE
"""

X = df_clean.drop(columns=['Outcome'])
y = df_clean['Outcome']

# Split data 80:20
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)
print(f'Data training : {len(X_train)} sampel')
print(f'Data testing  : {len(X_test)} sampel')

# Normalisasi MinMaxScaler
scaler = MinMaxScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# Resampling SMOTE
smote = SMOTE(random_state=42)
X_train_res, y_train_res = smote.fit_resample(X_train_scaled, y_train)
print(f'Target train setelah SMOTE: 0 = {(y_train_res == 0).sum()}, 1 = {(y_train_res == 1).sum()}')

"""## 5. Pemodelan & Evaluasi
- Decision Tree
- Naïve Bayes
- SVM
"""

models = {
    'Decision Tree': DecisionTreeClassifier(random_state=42, max_depth=5, criterion='gini'),
    'Naïve Bayes': GaussianNB(),
    'SVM': SVC(kernel='rbf', C=1.0, probability=True, random_state=42)
}

hasil_list = []
pred_dict = {}

for nama, model in models.items():
    print('=' * 60)
    print(f'Model: {nama}')
    print('=' * 60)

    # Training & prediksi
    model.fit(X_train_res, y_train_res)
    y_pred = model.predict(X_test_scaled)
    pred_dict[nama] = y_pred

    # Instance prediksi
    print(f'Instance Prediksi {nama}:')
    print(y_pred)

    # Metrik evaluasi
    acc = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred)
    rec = recall_score(y_test, y_pred)
    f1 = f1_score(y_test, y_pred)
    cm = confusion_matrix(y_test, y_pred)

    TN = cm[0, 0]
    FP = cm[0, 1]
    FN = cm[1, 0]
    TP = cm[1, 1]
    sensitivitas = TP / (TP + FN)
    spesifisitas = TN / (TN + FP)

    print(f'\nConfusion Matrix:')
    print(cm)
    print(f'- Akurasi      : {acc * 100:.2f} %')
    print(f'- Presisi      : {prec * 100:.2f} %')
    print(f'- Sensitivitas : {sensitivitas * 100:.2f} %')
    print(f'- Spesifisitas : {spesifisitas * 100:.2f} %')
    print(f'- F1-Score     : {f1:.4f}')

    print(f'\nClassification Report:')
    print(classification_report(y_test, y_pred, target_names=['Non-Diabetes (0)', 'Diabetes (1)']))

    hasil_list.append({
        'Model': nama,
        'Akurasi (%)': round(acc * 100, 2),
        'Presisi (%)': round(prec * 100, 2),
        'Recall (%)': round(sensitivitas * 100, 2),
        'Spesifisitas (%)': round(spesifisitas * 100, 2),
        'F1-Score': round(f1, 4),
        'Objek': model
    })

"""## 6. Perbandingan Model & Save Model
- Tabel evaluasi performa
- Simpan model terbaik (.joblib)
"""

df_hasil = pd.DataFrame(hasil_list)
print('=' * 60)
print('TABEL PERBANDINGAN MODEL'.center(60))
print('=' * 60)
print(df_hasil.drop(columns=['Objek']).to_string(index=False))

# Penentuan model terbaik
best_row = df_hasil.sort_values(by='Akurasi (%)', ascending=False).iloc[0]
best_model_name = best_row['Model']
best_model_obj = best_row['Objek']
print(f'\nModel terbaik: {best_model_name} ({best_row["Akurasi (%)"]} %)')

# Simpan model dan scaler
models_dir = 'models' if os.path.exists('models') else 'TM8/models'
os.makedirs(models_dir, exist_ok=True)
joblib.dump(best_model_obj, os.path.join(models_dir, 'best_model.joblib'))
joblib.dump(scaler, os.path.join(models_dir, 'scaler.joblib'))
joblib.dump(list(X.columns), os.path.join(models_dir, 'feature_names.joblib'))
print(f'Model ({best_model_name}) dan Scaler berhasil disimpan di {models_dir}/')

"""## 7. Visualisasi Confusion Matrix"""

fig, axes = plt.subplots(1, 3, figsize=(15, 4))
for idx, (nama, y_pred) in enumerate(pred_dict.items()):
    cm = confusion_matrix(y_test, y_pred)
    sns.heatmap(
        cm, annot=True, fmt='d', cmap='Blues', cbar=False, ax=axes[idx],
        xticklabels=['Non-Diabetes', 'Diabetes'],
        yticklabels=['Non-Diabetes', 'Diabetes']
    )
    axes[idx].set_title(f'Confusion Matrix: {nama}')
    axes[idx].set_xlabel('Prediksi')
    axes[idx].set_ylabel('Aktual')

img_path = 'confusion_matrix_comparison.png' if not os.path.exists('TM8') else 'TM8/confusion_matrix_comparison.png'
plt.savefig(img_path)
plt.show()